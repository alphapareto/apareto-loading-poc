#!/usr/bin/env bash
# Source before installing or running. The repository holds code and R* bundles only; environments, caches, run
# outputs, the checkpoint and the stores live under APARETO_HOME (default ~/.apareto; apareto_loader/paths.py).
export APARETO_HOME="${APARETO_HOME:-$HOME/.apareto}"
APARETO_CACHE_DIR="$APARETO_HOME/cache"
export XDG_CACHE_HOME="$APARETO_CACHE_DIR"
export XDG_CONFIG_HOME="$APARETO_CACHE_DIR/config"
export UV_CACHE_DIR="$APARETO_CACHE_DIR/uv"
export UV_PYTHON_INSTALL_DIR="$APARETO_CACHE_DIR/python"
export PIP_CACHE_DIR="$APARETO_CACHE_DIR/pip"
export HF_HOME="$APARETO_CACHE_DIR/huggingface"
export HF_HUB_CACHE="$HF_HOME/hub"
export HF_DATASETS_CACHE="$HF_HOME/datasets"
export TORCH_HOME="$APARETO_CACHE_DIR/torch"
export TORCH_EXTENSIONS_DIR="$APARETO_CACHE_DIR/torch_extensions"
export TORCHINDUCTOR_CACHE_DIR="$APARETO_CACHE_DIR/torchinductor"
export TRITON_CACHE_DIR="$APARETO_CACHE_DIR/triton"
export CUDA_CACHE_PATH="$APARETO_CACHE_DIR/cuda"
export FLASHINFER_WORKSPACE_BASE="$APARETO_CACHE_DIR/flashinfer"
export VLLM_CACHE_ROOT="$APARETO_CACHE_DIR/vllm"
export VLLM_CONFIG_ROOT="$APARETO_CACHE_DIR/vllm_config"
export MPLCONFIGDIR="$APARETO_CACHE_DIR/matplotlib"
export NUMBA_CACHE_DIR="$APARETO_CACHE_DIR/numba"
export NLTK_DATA="$APARETO_CACHE_DIR/nltk_data"
export TMPDIR="$APARETO_CACHE_DIR/tmp"
export TEMP="$TMPDIR"
export TMP="$TMPDIR"
mkdir -p "$TMPDIR" "$APARETO_HOME/results"
